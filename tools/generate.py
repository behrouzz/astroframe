#!/usr/bin/env python3
"""Generate astroframe/src/*.js, index.js and index.d.ts from the SOFA C sources."""
import os, sys, re
sys.path.insert(0, os.path.dirname(__file__))
from c2js import *

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
CSRC = os.path.normpath(os.path.join(ROOT, '..', '20231011', 'c', 'src'))
OUT = os.path.join(ROOT, 'src')

HEADER = """// astroframe: derived from the IAU SOFA C library (release 2023-10-11), file %s.
// Mechanically translated to JavaScript by tools/c2js.py.
//
// This code uses routines and computations derived by the astroframe authors from software
// provided by SOFA under license, and does not itself constitute software provided by and/or
// endorsed by SOFA.  Differences from the original SOFA C code:
//   - the "iau" prefix is removed from routine names (SOFA license, clause 3c);
//   - output arguments passed by pointer in C are returned from the JavaScript function;
//   - C arrays and structures are JavaScript arrays and objects;
//   - C int/long arithmetic is emulated (integer division truncates);
//   - the numerical algorithms and constants are unchanged.
// See README.md.  License: %s
"""

LICENSE_STD = 'SOFA Software License, PART 1 of LICENSE-SOFA.txt.'
LICENSE_DAT = ('SOFA Software License, variant for the user-replaceable routine "dat", '
               'PART 2 of LICENSE-SOFA.txt.')


def render(tr, cname, only_report=False):
    f, sig, src, fn = tr.parsed[cname]
    fe = FuncEmitter(tr, f, sig, f['structs'])
    params, lines = fe.run()
    out = [HEADER % (fn, LICENSE_DAT if fn == 'dat.c' else LICENSE_STD)]
    imp = []
    if fe.imports_consts:
        imp.append("import { %s } from './constants.js';" % ', '.join(sorted(fe.imports_consts)))
    if fe.imports_helpers:
        imp.append("import { %s } from './util.js';" % ', '.join(sorted(fe.imports_helpers - {'structs'})))
    if fe.imports_types:
        imp.append("import { %s } from './types.js';" % ', '.join(sorted(fe.imports_types)))
    for nm in sorted(fe.imports_funcs):
        imp.append("import { %s } from './%s.js';" % (nm, nm))
    out += imp
    out.append('')
    if fe.hoisted:
        out += fe.hoisted
        out.append('')
    doc = doc_to_jsdoc(sig, sig.doc)
    doc.insert(1, ' * JS usage:  ' + js_usage(sig))
    doc.insert(2, ' *')
    out += doc
    out.append('export function %s(%s) {' % (sig.name, ', '.join(params)))
    out += ['  ' + l if l else l for l in lines]
    out.append('}')
    return '\n'.join(out) + '\n', fe


def main():
    tr = Translator(CSRC)
    probs = tr.load_all()
    for p in probs:
        print('DOC PROBLEM', p)
    os.makedirs(OUT, exist_ok=True)
    fails = []
    warns = []
    audit = []
    for cname in sorted(tr.parsed):
        try:
            code, fe = render(tr, cname)
        except Exception as e:
            fails.append((cname, repr(e)))
            continue
        for w in fe.warnings:
            warns.append((cname, w))
        for a in fe.audit:
            audit.append((cname, a))
        with open(os.path.join(OUT, tr.sigs[cname].name + '.js'), 'w', newline='\n') as fh:
            fh.write(code)
    for c, e in fails:
        print('FAIL', c, e)
    for c, w in warns:
        print('WARN', c, w)
    with open(os.path.join(HERE, 'audit.txt'), 'w') as fh:
        fh.write('Type-sensitive translations (reviewed by hand; regenerated by generate.py)\n')
        for c, a in audit:
            fh.write('%s: %s\n' % (c, a))
    print('audit entries:', len(audit))
    print('translated', len(tr.parsed) - len(fails), 'of', len(tr.parsed))
    return tr


if __name__ == '__main__':
    from support import write_support
    tr = main()
    write_support(tr, OUT)
