#!/usr/bin/env python3
"""Translate SOFA's own validation suite (t_sofa_c.c) into astroframe/test/t_sofa.mjs.

The same translator that produced the library is used, so the test exercises
both the translated functions and the call-site conventions.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
from c2js import *
from generate import CSRC, ROOT

TEST_OUT = os.path.join(ROOT, 'test')


def main():
    tr = Translator(CSRC)
    tr.load_all()
    tr.extra_funcs = {'viv', 'vvd'}
    src = open(os.path.join(CSRC, 't_sofa_c.c')).read()
    # The test functions share a status flag through the harness instead of a pointer.
    src = src.replace('(int *status)', '()')
    src = re.sub(r',\s*status\s*\)', ')', src)
    # cut the helper functions viv/vvd and main (hand-written in JS)
    start = src.index('static void t_a2af()')
    mainpos = src.index('int main(')
    body_src = src[start:mainpos]
    toks = tokenize(body_src)
    structs = dict(tr.structs)
    typedefs = dict(tr.typedefs)
    p = Parser(toks, structs, typedefs)
    funcs = []
    all_funcs, all_consts, all_types, all_helpers = set(), set(), set(), set()
    chunks = []
    while p.i < len(toks):
        s0 = p.i
        f = p.function()
        f['body_tokens'] = toks[s0:p.i]
        f['structs'] = structs
        fname = f['name']
        sig = Sig(f, {}, [])
        fe = FuncEmitter(tr, f, sig, structs)
        try:
            params, lines = fe.run()
        except Exception as e:
            print('FAIL', fname, repr(e))
            continue
        all_funcs |= fe.imports_funcs
        all_consts |= fe.imports_consts
        all_types |= fe.imports_types
        chunks.append((fname, fe, lines))
    out = []
    out.append('// Generated by tools/gen_tests.py from SOFA\'s t_sofa_c.c (release 2023-10-11).')
    out.append('// Run with: node test/t_sofa.mjs [-v]')
    names = sorted(all_funcs | all_consts | all_types)
    out.append("import {\n  %s,\n} from '../src/index.js';" % ',\n  '.join(names))
    out.append('''
const verbose = process.argv.includes('-v');
let status = 0;

function viv(ival, ivalok, func, test) {
  if (ival !== ivalok) {
    status = 1;
    console.log(`${func} failed: ${test} want ${ivalok} got ${ival}`);
  } else if (verbose) {
    console.log(`${func} passed: ${test} want ${ivalok} got ${ival}`);
  }
}

function vvd(val, valok, dval, func, test) {
  const a = val - valok;
  // NOTE: stricter than the C original, whose test `a != 0.0 && fabs(a) > fabs(dval)` is false for NaN
  // and therefore silently accepts NaN results.
  if (Number.isNaN(a) || (a !== 0.0 && Math.abs(a) > Math.abs(dval))) {
    const f = Math.abs(valok / a);
    status = 1;
    console.log(`${func} failed: ${test} want ${valok} got ${val} (1/${f.toPrecision(3)})`);
  } else if (verbose) {
    console.log(`${func} passed: ${test} want ${valok} got ${val}`);
  }
}
''')
    for fname, fe, lines in chunks:
        out.append('function %s() {' % fname)
        out += ['  ' + l if l else l for l in lines]
        out.append('}')
        out.append('')
    out.append('const tests = [%s];' % ', '.join(c[0] for c in chunks))
    out.append('''for (const t of tests) t();
if (status) {
  console.log('t_sofa: SOME TESTS FAILED');
  process.exitCode = 1;
} else {
  console.log(`t_sofa: all ${tests.length} test groups passed`);
}''')
    os.makedirs(TEST_OUT, exist_ok=True)
    with open(os.path.join(TEST_OUT, 't_sofa.mjs'), 'w', newline='\n') as fh:
        fh.write('\n'.join(out) + '\n')
    print('translated', len(chunks), 'test functions')


main()
